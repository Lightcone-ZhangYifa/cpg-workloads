#!/usr/bin/env python3
"""Build the locked HMMER snapshot with a byte-checked official Easel closure."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import tarfile
import traceback


def sha(path):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def main():
    parser = argparse.ArgumentParser()
    for name in ("source", "build", "prefix"):
        parser.add_argument("--" + name, type=Path, required=True)
    parser.add_argument("--jobs", type=int, default=2)
    args = parser.parse_args()
    source, build, prefix = (getattr(args, key).resolve() for key in ("source", "build", "prefix"))
    recipe = Path(__file__).parent
    config = json.loads((recipe / "config.json").read_text())
    raw = recipe / config["supplement"]["filename"]
    if raw.stat().st_size != config["supplement"]["bytes"] or sha(raw) != config["supplement"]["sha256"]:
        raise AssertionError("Official supplemental source distribution differs from its exact recipe lock")
    logs, combined, obj = build / "build-evidence", build / "combined-source", build / "obj"
    logs.mkdir(parents=True, exist_ok=False)
    obj.mkdir(parents=True, exist_ok=False)
    shutil.copytree(source, combined, symlinks=True)
    report = {"schema_version": 1, "resource": "hmmer", "status": "running", "configuration": config,
              "supplement": config["supplement"], "commands": [], "original_source_mutation": "none",
              "closure": {"matched": [], "added": []}, "upstream_tests": {"status": "not_run"}}
    environment = dict(os.environ)
    for name in ("LD_PRELOAD", "LD_LIBRARY_PATH", "CPATH", "LIBRARY_PATH", "CFLAGS", "CPPFLAGS", "LDFLAGS"):
        environment.pop(name, None)
    environment.update(PATH="/usr/bin:/bin", LC_ALL="C", HMMER_NCPU="1")

    def run(label, argv, *, cwd=obj, timeout=1800, expected=0):
        argv = [str(x) for x in argv]
        with (logs / (label + ".stdout")).open("wb") as out, (logs / (label + ".stderr")).open("wb") as err:
            result = subprocess.run(argv, cwd=cwd, env=environment, stdout=out, stderr=err, timeout=timeout)
        row = {"label": label, "argv": argv, "cwd": str(cwd), "returncode": result.returncode,
               "stdout": label + ".stdout", "stderr": label + ".stderr"}
        report["commands"].append(row)
        if result.returncode != expected:
            raise RuntimeError("Source deployment command failed: " + label)
        return row

    try:
        with tarfile.open(raw) as archive:
            for member in archive.getmembers():
                parts = Path(member.name).parts
                if not parts or parts[0] != "hmmer-3.4" or ".." in parts:
                    raise AssertionError("Unexpected official release archive member")
                if len(parts) == 1:
                    continue
                relative = Path(*parts[1:])
                target = combined / relative
                if member.isdir():
                    target.mkdir(parents=True, exist_ok=True)
                elif member.isfile():
                    content = archive.extractfile(member).read()
                    digest = hashlib.sha256(content).hexdigest()
                    if target.exists():
                        if not target.is_file() or target.is_symlink() or sha(target) != digest:
                            raise AssertionError("Supplement conflicts with original locked source: " + str(relative))
                        report["closure"]["matched"].append({"path": str(relative), "sha256": digest, "bytes": len(content)})
                    else:
                        target.parent.mkdir(parents=True, exist_ok=True)
                        target.write_bytes(content)
                        target.chmod(member.mode & 0o777)
                        report["closure"]["added"].append({"path": str(relative), "sha256": digest, "bytes": len(content)})
                else:
                    raise AssertionError("Unsupported link/special member in the supplemental release")
        if len(report["closure"]["matched"]) != 385:
            raise AssertionError("The expected complete common-source match changed")
        if "Easel 0.49 release notes" not in (combined / "easel/release-notes/RELEASE-0.49.md").read_text():
            raise AssertionError("Unexpected Easel release")
        if "Generated by GNU Autoconf 2.71 for HMMER 3.4" not in (combined / "configure").read_text():
            raise AssertionError("Unexpected generated configure identity")
        run("configure", ["/bin/sh", combined / "configure", "--prefix=" + str(prefix), *config["configure_options"]])
        run("make", ["/usr/bin/make", "-j" + str(min(2, max(1, args.jobs)))])
        run("make-tests", ["/usr/bin/make", "-j" + str(min(2, max(1, args.jobs))), "tests"])
        # SQC uses an unpinned Perl driver in this environment. Execute the
        # unchanged level-1/2 native command rows directly, with the original
        # SQC substitutions and expected return code. Script-driven integration,
        # MPI, Valgrind and architecture no-op stubs remain explicitly excluded.
        testwork = build / "upstream-native-work"
        testwork.mkdir()
        selected, skipped, preparation = [], [], []
        for suite, relative, top_build, top_source in (
                ("hmmer", "testsuite/testsuite.sqc", obj, combined),
                ("easel", "easel/testsuite/testsuite.sqc", obj / "easel", combined / "easel")):
            sqc = combined / relative
            scope = testwork / suite
            scope.mkdir()
            for lineno, line in enumerate(sqc.read_text().splitlines(), 1):
                if not line.strip() or line.lstrip().startswith("#"):
                    continue
                fields = line.split(None, 3)
                if len(fields) != 4 or not fields[0].isdigit():
                    raise AssertionError("Unexpected SQC row")
                level, kind, name, command = fields
                if int(level) > 2:
                    skipped.append({"suite": suite, "line": lineno, "name": name, "reason": "Higher test level outside selected profile"})
                    continue
                native = re.match(r"@([^@]+)@", command)
                is_cleanup = kind == "prep" and command.startswith("rm ")
                if kind not in {"prep", "exercise"} or not (native or is_cleanup):
                    skipped.append({"suite": suite, "line": lineno, "name": name, "reason": "Non-native/script-driven SQC row; no Perl deployment claimed"})
                    continue
                if native and Path(native.group(1)).name in {"esl_neon_utest", "esl_vmx_utest", "esl_avx_utest", "esl_avx512_utest"}:
                    skipped.append({"suite": suite, "line": lineno, "name": name, "reason": "Architecture-specific optional test/no-op stub outside SSE2 profile"})
                    continue
                native_identity = None
                if native:
                    executable = top_build / native.group(1)
                    if not executable.is_file() or executable.open("rb").read(4) != b"\x7fELF":
                        raise AssertionError("Selected native SQC command is not a built ELF executable: " + str(executable))
                    native_identity = {"path": str(executable), "sha256": sha(executable), "bytes": executable.stat().st_size,
                                       "format": "ELF", "source_command": native.group(1)}
                command = re.sub(r"@([^@]*)@", lambda match: shlex.quote(str(top_build / match.group(1))), command)
                command = re.sub(r"!([^!]*)!", lambda match: shlex.quote(str(top_source / match.group(1))), command)
                command = re.sub(r"%([^%]+)%", lambda match: shlex.quote(str(scope / match.group(1))), command)
                label = f"upstream-{suite}-{lineno:04d}"
                result = run(label, ["/bin/sh", "-c", command], cwd=scope, timeout=180)
                case = {"suite": suite, "sqc_file": relative, "sqc_sha256": sha(sqc), "line": lineno,
                        "name": name, "kind": kind, "original_command": fields[3], "native_executable": native_identity, **result}
                (preparation if kind == "prep" else selected).append(case)
        actual_counts = {suite: sum(row["suite"] == suite for row in selected) for suite in ("hmmer", "easel")}
        if actual_counts != {"hmmer": 282, "easel": 65} or len(preparation) != 17:
            raise AssertionError("The fixed native upstream selection was incomplete or changed")
        report["upstream_tests"] = {"status": "passed", "suite": "Unchanged HMMER/Easel level-1/2 native SQC command rows",
                                    "executed": len(selected), "passed": len(selected), "failed": 0,
                                    "selected_counts": actual_counts, "preparation_commands": len(preparation),
                                    "excluded_count": len(skipped), "tests": selected, "preparation": preparation,
                                    "excluded": skipped, "full_make_check": "not_run: its Perl driver/runtime has no matching system-package pin"}
        run("install", ["/usr/bin/make", "install"])
        run("install-easel", ["/usr/bin/make", "-C", "easel", "install"])
        shutil.copytree(source, prefix / "share/hmmer/source", symlinks=True)
        supplement = prefix / "share/hmmer/supplements"
        supplement.mkdir(parents=True, exist_ok=True)
        shutil.copy2(raw, supplement / raw.name)
        # The full supplemental archive is retained independently. Developers
        # can inspect/extract all Easel source, tests and release documentation.
        for name in ("config.log", "src/p7_config.h", "easel/esl_config.h"):
            shutil.copy2(obj / name, logs / name.replace("/", "-"))
        report["status"] = "passed"
    except Exception as error:
        report.update(status="failed", error=f"{type(error).__name__}: {error}", traceback=traceback.format_exc())
        raise
    finally:
        (logs / "build-report.json").write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
        if report["status"] == "passed":
            evidence = prefix / "share/compiler-playground/hmmer"
            evidence.mkdir(parents=True, exist_ok=True)
            shutil.copytree(logs, evidence / "build-evidence")
            (evidence / "profile.json").write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
