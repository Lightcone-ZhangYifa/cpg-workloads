#!/usr/bin/env python3
"""Offline, bounded LLVM capability checks. No tool lookup or acquisition."""
from __future__ import annotations

import argparse
import difflib
import hashlib
import json
import os
import re
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import time


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def verify_payload(root, lock_path):
    root = Path(root).resolve(strict=True)
    lock = json.loads(Path(lock_path).read_text())
    for record in lock['files']:
        path = root/record['path']
        if record.get('kind') == 'symlink':
            if not path.is_symlink() or os.readlink(path) != record['target']:
                raise ValueError('Dependency symlink changed: '+str(path))
            if not path.resolve().is_relative_to(root):
                raise ValueError('Dependency symlink leaves prepared prefix: '+str(path))
        elif path.is_symlink() or not path.is_file() or path.stat().st_size != record['bytes'] or sha(path) != record['sha256']:
            raise ValueError('Prepared dependency binding changed: '+str(path))
    return lock


class Audit:
    def __init__(self, root, output):
        self.root = Path(root).resolve(strict=True)
        self.output = Path(output).resolve()
        self.output.mkdir(parents=True, exist_ok=True)
        self.commands = []
        self.env = {**os.environ, 'LC_ALL': 'C', 'LANG': 'C',
                    'LLVM_DISABLE_CRASH_REPORT': '1', 'DEBUGINFOD_URLS': '',
                    'PYTHONDONTWRITEBYTECODE': '1'}

    def run(self, name, argv, *, expected=0, stdin=None, timeout=180, cwd=None, env=None):
        start = time.time()
        result = subprocess.run([str(x) for x in argv], input=stdin, capture_output=True,
                                timeout=timeout, cwd=cwd or self.output,
                                env={**self.env, **(env or {})})
        (self.output/(name+'.stdout')).write_bytes(result.stdout)
        (self.output/(name+'.stderr')).write_bytes(result.stderr)
        row = dict(name=name, argv=[str(x) for x in argv], returncode=result.returncode,
                   expected_returncode=expected, elapsed_seconds=time.time()-start,
                   stdout_sha256=hashlib.sha256(result.stdout).hexdigest(),
                   stderr_sha256=hashlib.sha256(result.stderr).hexdigest())
        self.commands.append(row)
        (self.output/'commands.json').write_text(json.dumps(self.commands, indent=2))
        if result.returncode != expected:
            raise RuntimeError(f'{name}: expected {expected}, got {result.returncode}: '
                               + result.stderr[-4000:].decode(errors='replace'))
        return result

    def tool(self, name):
        return self.root/'bin'/name

    def validate(self, lock, names):
        expected = json.loads(Path(lock).read_text())
        if expected['llvm_revision'] != '7a941dfb2877a0b8cf30323fefa85ad019e0b0f5':
            raise ValueError('Unexpected LLVM source revision')
        records = {r['path']: r for r in expected['files']}
        checked = []
        for name in names:
            path = 'bin/'+name
            record = records[path]
            actual = self.root/path
            if actual.stat().st_size != record['bytes'] or sha(actual) != record['sha256']:
                raise ValueError('Toolchain binding differs from admitted bytes: '+path)
            checked.append(record)
        for path, record in records.items():
            if path.startswith(('share/llvm-source/', 'lib/')):
                actual = self.root/path
                if sha(actual) != record['sha256']:
                    raise ValueError('Source-version helper/runtime closure changed: '+path)
        (self.output/'verified-tool-bindings.json').write_text(json.dumps(checked, indent=2))


def authoring(a):
    source = a.output/'baseline.ll'
    source.write_text('; RUN: opt -passes=instcombine -S < %s | FileCheck %s\n\n'
                      'define i32 @fold(i32 %x) {\nentry:\n'
                      '  %sum = add i32 %x, 0\n  ret i32 %sum\n}\n')
    script = a.root/'share/llvm-source/llvm/utils/update_test_checks.py'
    a.run('generate-baseline-checks', [sys.executable, script, '--opt-binary', a.tool('opt'), source])
    baseline = source.read_text()
    if 'CHECK-NEXT:' not in baseline or 'Assertions have been autogenerated' not in baseline:
        raise AssertionError('The source-version generator did not author CHECK directives')
    optimized = a.run('opt-baseline', [a.tool('opt'), '-passes=instcombine', '-S', source])
    a.run('filecheck-baseline', [a.tool('FileCheck'), source], stdin=optimized.stdout)
    candidate = a.output/'candidate.ll'
    candidate.write_text(baseline.replace('add i32 %x, 0', 'add i32 %x, 7'))
    a.run('generate-candidate-checks', [sys.executable, script, '--opt-binary', a.tool('opt'), candidate])
    optimized_candidate = a.run('opt-candidate', [a.tool('opt'), '-passes=instcombine', '-S', candidate])
    a.run('filecheck-candidate', [a.tool('FileCheck'), candidate], stdin=optimized_candidate.stdout)
    a.run('reject-stale-baseline-checks', [a.tool('FileCheck'), source], stdin=optimized_candidate.stdout, expected=1)
    diff = ''.join(difflib.unified_diff(baseline.splitlines(True), candidate.read_text().splitlines(True),
                                      fromfile='baseline.ll', tofile='candidate.ll'))
    if not diff or '+; CHECK-NEXT:' not in diff:
        raise AssertionError('The baseline/candidate CHECK delta is not reviewable')
    (a.output/'baseline-candidate.diff').write_text(diff)
    return {'source_version_check_generator': 'passed', 'positive_cases': 2,
            'stale_expectation_rejected': True, 'reviewable_diff': 'baseline-candidate.diff'}


def filecheck_lit(a):
    checks = a.output/'patterns.check'
    checks.write_text('CHECK-LABEL: begin\nCHECK-NEXT: value 42\nCHECK-DAG: left\nCHECK-DAG: right\nCHECK-NOT: forbidden\nCHECK: end\n')
    a.run('filecheck-patterns', [a.tool('FileCheck'), checks], stdin=b'begin\nvalue 42\nright\nleft\nend\n')
    a.run('filecheck-negative', [a.tool('FileCheck'), checks], stdin=b'begin\nvalue 43\nright\nleft\nend\n', expected=1)
    suite = a.output/'lit-suite'
    suite.mkdir()
    (suite/'lit.cfg.py').write_text(
        'import lit.formats\nconfig.name="cpg-llvm23"\nconfig.test_format=lit.formats.ShTest(False)\n'
        'config.suffixes=[".test"]\nconfig.test_source_root=__file__.rsplit("/",1)[0]\n'
        f'config.substitutions.append(("%FileCheck", {str(a.tool("FileCheck"))!r}))\n')
    (suite/'pass.test').write_text('# RUN: printf "value 42\\n" | %FileCheck %s\n# CHECK: value 42\n')
    (suite/'xfail.test').write_text('# XFAIL: *\n# RUN: false\n')
    (suite/'unsupported.test').write_text('# REQUIRES: missing-cpg-feature\n# RUN: false\n')
    lit = a.root/'share/llvm-source/llvm/utils/lit/lit.py'
    a.run('lit-real-suite', [sys.executable, lit, '-v', '-j1', '-o', a.output/'lit.json', suite])
    report = json.loads((a.output/'lit.json').read_text())
    codes = sorted(row['code'] for row in report['tests'])
    if codes != ['PASS', 'UNSUPPORTED', 'XFAIL']:
        raise AssertionError('lit semantics changed: '+repr(codes))
    (suite/'bad.test').write_text('# RUN: printf "wrong\\n" | %FileCheck %s\n# CHECK: right\n')
    a.run('lit-reject-failing-test', [sys.executable, lit, '-v', '-j1', suite/'bad.test'], expected=1)
    return {'FileCheck_positive_and_negative': 'passed', 'lit_codes': codes,
            'unexpected_failure_rejected': True}


def debug_info(a, debuggers=None):
    ir = a.output/'plain.ll'
    ir.write_text('define i32 @id(i32 %x) {\nentry:\n  %a = add i32 %x, 1\n  ret i32 %a\n}\n')
    synthetic = a.run('debugify-synthetic', [a.tool('opt'), '-passes=debugify,instcombine,check-debugify', '-S', ir])
    if b'PASS' not in synthetic.stderr:
        raise AssertionError('No successful synthetic debugify diagnostic')
    broken = a.run('debugify-negative', [a.tool('opt'), '-passes=debugify,strip,check-debugify', '-S', ir])
    # Debugify reports diagnostics rather than establishing semantic equivalence.
    if b'Skipping module without debugify metadata' not in broken.stderr and b'WARNING' not in broken.stderr:
        raise AssertionError('The stripped-debug negative control was not detected')
    c = a.output/'debug.c'
    c.write_text('#include <stdio.h>\n__attribute__((noinline)) int twice(int x) {\n'
                 '  int y = x * 2;\n  return y + 1;\n}\n'
                 'int main(void) { printf("%d\\n", twice(5)); return 0; }\n')
    original = a.output/'original.ll'
    preserved = a.output/'preserved.ll'
    a.run('clang-original-di', [a.tool('clang'), '-g', '-O0', '-Xclang', '-disable-O0-optnone',
                               '-emit-llvm', '-S', c, '-o', original])
    ssa = a.output/'original-ssa.ll'
    a.run('prepare-original-di-ssa', [a.tool('opt'), '-passes=mem2reg', '-S', original, '-o', ssa])
    di = a.run('original-di-preservation', [a.tool('opt'), '-passes=instcombine', '-verify-debuginfo-preserve',
                                           '-S', ssa, '-o', preserved])
    diagnostics = di.stdout + di.stderr
    if any(word in diagnostics for word in (b'WARNING', b'ERROR', b'FAIL')):
        raise AssertionError('Original debug-info preservation reported a problem')
    if b'CheckModuleDebugify (original debuginfo): PASS' not in diagnostics:
        raise AssertionError('Original debug-info preservation did not explicitly pass')
    stripped = a.run('original-di-negative-strip', [a.tool('opt'), '-passes=strip',
                    '-verify-debuginfo-preserve', '-S', ssa, '-o', a.output/'stripped.ll'])
    if b'Skipping module without debug info' not in stripped.stdout+stripped.stderr:
        raise AssertionError('Original debug-info removal was not explicitly uncheckable')
    if '!DICompileUnit' in (a.output/'stripped.ll').read_text():
        raise AssertionError('Strip negative control still contained a compile unit')
    # Preserve the compilation unit but deliberately remove one real source
    # location. This exercises LLVM's exit-zero WARNING/FAIL diagnostics.
    missing_loc = a.output/'original-missing-location.ll'
    negative_text, replacements = re.subn(r'(^\s*ret[^\n]*), !dbg !\d+', r'\1',
                                          ssa.read_text(), count=1, flags=re.MULTILINE)
    if replacements != 1:
        raise AssertionError('Unable to construct location-removal negative control')
    missing_loc.write_text(negative_text)
    location_failure = a.run('original-di-negative-location', [a.tool('opt'),
        '-passes=instcombine', '-verify-debuginfo-preserve', '-S', missing_loc,
        '-o', a.output/'missing-location-after.ll'])
    negative_diagnostics = location_failure.stdout+location_failure.stderr
    if b'WARNING' not in negative_diagnostics or b'FAIL' not in negative_diagnostics:
        raise AssertionError('Original location-removal WARNING/FAIL was not detected')
    if '!DICompileUnit' not in preserved.read_text() or '!DILocalVariable' not in preserved.read_text():
        raise AssertionError('Original debug information was not preserved')
    program = a.output/'debug-program'
    a.run('clang-dwarf-object', [a.tool('clang'), '-g', '-gdwarf-5', '-O1', c, '-o', program])
    a.run('dwarf-verify', [a.tool('llvm-dwarfdump'), '--verify', program])
    bad_object = a.output/'truncated-object'
    bad_object.write_bytes(program.read_bytes()[:40])
    a.run('dwarf-reject-truncated-object', [a.tool('llvm-dwarfdump'), '--verify', bad_object], expected=1)
    output = a.run('executable-output-separate', [program])
    if output.stdout != b'11\n':
        raise AssertionError('Executable-output oracle failed')
    result = {'synthetic_debugify': 'passed', 'missing_debug_negative': 'passed',
              'original_debug_info': 'passed', 'original_location_removal_negative': 'WARNING/FAIL despite exit 0',
              'original_debug_removal_negative': 'explicitly uncheckable; not qualified',
              'DWARF5': 'passed', 'output_oracle': '11'}
    if debuggers:
        root = Path(debuggers).resolve(strict=True)
        environment = {'LD_LIBRARY_PATH': str(root/'usr/lib/x86_64-linux-gnu'),
                       'PYTHONHOME': str(root/'usr'), 'DEBUGINFOD_URLS': '',
                       'PYTHONPATH': str(root/'usr/lib/llvm-18/lib/python3.12/site-packages')}
        gdb = a.run('gdb-dwarf-consumer', [root/'usr/bin/gdb', '-nx', '-batch',
                    '-ex', 'set debuginfod enabled off', '-ex', 'info functions twice',
                    '-ex', 'info line twice', program], env=environment)
        lldb = a.run('lldb-dwarf-consumer', [root/'usr/lib/llvm-18/bin/lldb', '--no-lldbinit', '--batch',
                    '-o', 'target create '+str(program), '-o', 'image lookup -n twice -v'], env=environment)
        if b'twice' not in gdb.stdout or b'debug.c' not in gdb.stdout:
            raise AssertionError('GDB did not consume function/source-line DWARF')
        if b'twice' not in lldb.stdout or b'debug.c' not in lldb.stdout:
            raise AssertionError('LLDB did not consume function/source-line DWARF')
        result['cross_debugger_DWARF_consumers'] = ['GDB15', 'LLDB18']
        result['cross_debugger_scope'] = 'symbol/source-line decoding; live ptrace stepping is not claimed'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('kind', choices=['authoring', 'filecheck-lit', 'debug-info'])
    parser.add_argument('--toolchain', required=True)
    parser.add_argument('--lock', required=True)
    parser.add_argument('--output')
    parser.add_argument('--debuggers')
    parser.add_argument('--debuggers-lock')
    parser.add_argument('--output-parent')
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix='cpg-llvm-check-') as temporary:
        if args.output_parent:
            parent = Path(args.output_parent)
            parent.mkdir(parents=True, exist_ok=True)
            output = Path(tempfile.mkdtemp(prefix=args.kind+'-', dir=parent))
        else:
            output = Path(args.output) if args.output else Path(temporary)
        audit = Audit(args.toolchain, output)
        needed = {'authoring':['opt','FileCheck'], 'filecheck-lit':['FileCheck'],
                  'debug-info':['opt','clang','llvm-dwarfdump']}[args.kind]
        audit.validate(args.lock, needed)
        if args.debuggers:
            if not args.debuggers_lock:
                parser.error('--debuggers requires an immutable --debuggers-lock')
            verify_payload(args.debuggers, args.debuggers_lock)
        result = (authoring(audit) if args.kind == 'authoring' else
                  filecheck_lit(audit) if args.kind == 'filecheck-lit' else
                  debug_info(audit, args.debuggers))
        audit.validate(args.lock, needed)
        if args.debuggers:
            verify_payload(args.debuggers, args.debuggers_lock)
        result.update(schema_version=1, status='passed', capability=args.kind,
                      commands=len(audit.commands), network_used=False,
                      llvm_revision='7a941dfb2877a0b8cf30323fefa85ad019e0b0f5',
                      performance_claim=False)
        (output/'result.json').write_text(json.dumps(result, indent=2))
        print(json.dumps(result, sort_keys=True))


if __name__ == '__main__':
    main()
