#!/usr/bin/env python3
"""Offline d8 functionality check; all generated output stays outside PREFIX."""
import argparse
import hashlib
import json
import os
import re
import shlex
import subprocess
import tempfile
from pathlib import Path


def digest(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def check(prefix, work):
    prefix = prefix.resolve(strict=True)
    work = work.resolve(strict=True)
    if work == prefix or prefix in work.parents:
        raise ValueError("check output directory must be outside installed prefix")
    lock = json.loads((prefix / "materials/runtime-inputs.json").read_text())
    for item in lock["files"]:
        path = prefix / item["path"]
        if path.is_symlink() or not path.is_file():
            raise ValueError("missing or linked input: " + item["path"])
        if path.stat().st_size != item["bytes"] or digest(path) != item["sha256"]:
            raise ValueError("input integrity failure: " + item["path"])
    d8 = prefix / "engine/d8"
    upstream = prefix / "upstream"
    calls = []

    def run(label, argv, timeout=90):
        result = subprocess.run([str(x) for x in argv], cwd=work,
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                text=True, timeout=timeout, check=False)
        stdout = work / (label + ".stdout.txt")
        stderr = work / (label + ".stderr.txt")
        stdout.write_text(result.stdout)
        stderr.write_text(result.stderr)
        record = {"label": label, "argv": [str(x) for x in argv],
                  "exit_code": result.returncode, "stdout_sha256": digest(stdout),
                  "stderr_sha256": digest(stderr)}
        calls.append(record)
        (work / "commands.json").write_text(json.dumps(calls, indent=2) + "\n")
        combined = result.stdout + result.stderr
        if result.returncode != 0:
            raise RuntimeError(label + ": exit " + str(result.returncode) + "\n" + combined[-8000:])
        if re.search(r"unrecognized flag|unknown flag|skipping test|test is skipped", combined, re.I):
            raise RuntimeError(label + ": a flag or test was skipped\n" + combined[-8000:])
        return result.stdout

    version = run("version", [d8, "--version"]).strip()
    if version != "V8 version " + lock["version"]:
        raise ValueError("unexpected installed V8 version: " + version)
    deps = run("ldd", ["ldd", d8])
    if "not found" in deps:
        raise RuntimeError("unresolved shared library")
    probe = prefix / "checks/type-change.js"
    expected = [["integer",42],["object",42],["string_type_change","411"],
                ["object_shape_change",42],["float_type_change",1.5],
                ["negative_zero",1],["null_coercion",1],["back_to_integer",42],
                ["back_to_original_shape",42]]
    harness = (upstream / "test/mjsunit/mjsunit.js").read_text()
    masks = {}
    for key in ["kOptimized", "kTurboFanned", "kMaglevved"]:
        match = re.search(r"\b" + key + r":\s*1\s*<<\s*(\d+)", harness)
        if not match:
            raise ValueError("upstream optimization status enum not found")
        masks[key] = 1 << int(match.group(1))
    probes = {}
    for mode in ["interpreter", "optimized", "maglev"]:
        flags = ["--jitless", "--print-bytecode", "--print-bytecode-filter=addOne"] if mode == "interpreter" else [
            "--allow-natives-syntax", "--no-concurrent-recompilation", "--trace-opt", "--trace-deopt"]
        out = run("probe-" + mode, [d8, *flags, probe, "--", mode])
        matches = re.findall(r"^RESULT=(.+)$", out, re.M)
        if len(matches) != 1 or json.loads(matches[0]) != expected:
            raise ValueError("semantic result mismatch in " + mode)
        item = {"semantic_cases": len(expected), "result": expected}
        if mode == "interpreter":
            if "generated bytecode for function: addOne" not in out:
                raise ValueError("Ignition bytecode evidence missing")
            item["bytecode_observed"] = True
        else:
            before = json.loads(re.search(r"^STATUS_BEFORE=(.+)$", out, re.M).group(1))
            after = json.loads(re.search(r"^STATUS_AFTER=(.+)$", out, re.M).group(1))
            tier, mask = ("TURBOFAN_JS", masks["kTurboFanned"]) if mode == "optimized" else ("MAGLEV", masks["kMaglevved"])
            for fn, reason in [("addOne", "not a Smi"), ("fieldPlusOne", "wrong map")]:
                if not before[fn] & masks["kOptimized"] or not before[fn] & mask:
                    raise ValueError("optimized state missing: " + fn + "/" + tier)
                if after[fn] & masks["kOptimized"]:
                    raise ValueError("function remained optimized after type/shape change")
                if not any("completed compiling" in line and "<JSFunction " + fn + " " in line and "target " + tier in line for line in out.splitlines()):
                    raise ValueError("completed compiler event missing: " + fn)
                if not any("bailout" in line and "deoptimizing" in line and "reason: " + reason in line and "<JSFunction " + fn + " " in line for line in out.splitlines()):
                    raise ValueError("deoptimization event missing: " + fn)
            item.update(tier=tier, optimization_status_before=before,
                        optimization_status_after=after,
                        deoptimization_reasons=["not a Smi", "wrong map"])
        probes[mode] = item

    selected = json.loads((prefix / "materials/selected-source-files.json").read_text())
    cases = []
    for name in selected["selected_tests"]:
        test = upstream / "test/mjsunit" / name
        text = test.read_text()
        flags = [flag for line in re.findall(r"^//\s+Flags:(.*)$", text, re.M) for flag in shlex.split(line)]
        # This fixed subset has no additional Files:/environment/NO HARNESS directives.
        if re.search(r"^//\s+(?:Files:|Environment Variables:|NO HARNESS)", text, re.M):
            raise ValueError("additional runner directives require explicit handling: " + name)
        label = "mjsunit-" + name.replace("/", "__").removesuffix(".js")
        run(label, [d8, *flags, upstream / "test/mjsunit/mjsunit.js", test])
        cases.append({"name":name,"flags":flags,"status":"passed"})
    result = {"resource_id":"runtime.v8", "status":"passed", "version":lock["version"],
              "source_commit":lock["source_commit"], "input_files_verified":len(lock["files"]),
              "execution_mode":"offline official prebuilt d8",
              "semantic_equality":True, "probes":probes,
              "upstream_cases":cases, "upstream_passed":len(cases),
              "upstream_failed":0, "upstream_skipped":0,
              "command_count":len(calls), "source_build_verified":False,
              "full_upstream_suite_verified":False, "official_benchmark_verified":False}
    (work / "result.json").write_text(json.dumps(result, indent=2) + "\n")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prefix", type=Path, required=True)
    parser.add_argument("--evidence-dir", type=Path)
    args = parser.parse_args()
    if args.evidence_dir:
        args.evidence_dir.mkdir(parents=True, exist_ok=False)
        result = check(args.prefix, args.evidence_dir)
    else:
        with tempfile.TemporaryDirectory(prefix="cpg-v8-check-") as temp:
            result = check(args.prefix, Path(temp))
    print(json.dumps(result, sort_keys=True))


if __name__ == "__main__":
    main()
